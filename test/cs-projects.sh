#!/usr/bin/env bash
# Write the `.csproj` files that let a C# language server open the tests.
#
# The build does not use these — `build-cs.sh` synthesises a stock project instead, since
# the obligation it checks is that annotated C# is ordinary C#, and a project that loaded
# pal-csharp's own analyzer would not be checking that. These are for the editor: with one
# of them loaded, opening a test file shows exactly what `palcs` would say about it,
# because the analyzer runs the translator's own passes.
#
# They are generated for the same reason `fst-configs.sh` generates its configs: an editor
# that disagrees with the build about what a directory contains is worse than an editor
# that knows nothing about it. Each project is four lines and defers everything to
# `test/pal-tests.props`.
#
#   bash test/cs-projects.sh           write (or refresh) every project
#   bash test/cs-projects.sh --check   fail if any is missing or stale
#
# `--check` runs in the test suite, so a directory added to the tree cannot be left
# without one.
set -uo pipefail

cd "$(dirname "$0")/.."
ROOT=$(pwd)

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

status=0
count=0
projects=()

# Arguments: <directory relative to the repo root> <path from it to pal-tests.props>
write_project() {
    local dir=$1 props=$2
    local name file body
    name=$(basename "$dir")
    file="$dir/$name.csproj"

    body="<!-- Generated by test/cs-projects.sh. Edit that, or test/pal-tests.props. -->
<Project Sdk=\"Microsoft.NET.Sdk\">
  <Import Project=\"$props\" />
</Project>"

    count=$((count + 1))
    projects+=("${file#"$ROOT"/}")

    if [ "$CHECK" = 1 ]; then
        if [ ! -f "$file" ]; then
            echo "cs-projects: missing $file"
            status=1
        elif ! diff -q <(printf '%s\n' "$body") "$file" >/dev/null; then
            echo "cs-projects: stale $file (run 'bash test/cs-projects.sh')"
            status=1
        fi
    else
        printf '%s\n' "$body" > "$file"
    fi
}

# An acceptance directory: a Makefile that includes verify.mk, and C# to translate.
for dir in "$ROOT"/test/*/; do
    dir=${dir%/}
    grep -q 'verify\.mk' "$dir/Makefile" 2>/dev/null || continue
    compgen -G "$dir/*.cs" > /dev/null || continue
    write_project "$dir" "../pal-tests.props"
done

# The negative cases, which are the interesting ones to look at: every file in here is
# meant to be red. They share one project because they are standalone and their type names
# do not collide, and because each one's diagnostics land on its own file — a case cannot
# provoke a diagnostic in another case, so the editor shows what `palcs` shows for each.
write_project "$ROOT/test/diagnostics/cases" "../../pal-tests.props"

# One solution listing all of them, so that an editor loads the whole tree at once rather
# than whichever project happens to sit beside the file that was opened first. It is
# written here, from the same list, because a solution that has to be updated by hand when
# a directory is added is a solution that is wrong a week later.
#
# `Pal.slnx` stays as it is: it is what `make build` and CI build, and it must go on
# containing only the product. This one is an editor artifact, and it is *expected* to be
# red — `test/diagnostics/cases` is twenty-two programs that are supposed to be refused.
#
# It is a classic `.sln` rather than the newer `.slnx` the product uses because the C#
# extension's solution discovery still looks for `.sln`. The GUIDs are derived from the
# project's path so that regenerating the file produces the same bytes.
guid_for() {
    local h
    h=$(printf '%s' "$1" | md5sum | cut -c1-32 | tr 'a-f' 'A-F')
    echo "{${h:0:8}-${h:8:4}-${h:12:4}-${h:16:4}-${h:20:12}}"
}

CSPROJ_TYPE="{9A19103F-16F7-4668-BE54-9A1E7A4F7556}"
SLN="$ROOT/Pal.Tests.sln"

sln_text() {
    local all=("src/Pal.Annotations/Pal.Annotations.csproj"
               "src/Pal.Compiler/Pal.Compiler.csproj"
               "src/Pal.Analyzers/Pal.Analyzers.csproj"
               "src/Pal.Tool/Pal.Tool.csproj"
               "${projects[@]}")

    printf 'Microsoft Visual Studio Solution File, Format Version 12.00\n'
    printf '# Generated by test/cs-projects.sh -- do not edit.\n'
    local p name g
    for p in "${all[@]}"; do
        name=$(basename "$p" .csproj)
        g=$(guid_for "$p")
        printf 'Project("%s") = "%s", "%s", "%s"\nEndProject\n' "$CSPROJ_TYPE" "$name" "$p" "$g"
    done
    printf 'Global\n'
    printf '\tGlobalSection(SolutionConfigurationPlatforms) = preSolution\n'
    printf '\t\tDebug|Any CPU = Debug|Any CPU\n'
    printf '\t\tRelease|Any CPU = Release|Any CPU\n'
    printf '\tEndGlobalSection\n'
    printf '\tGlobalSection(ProjectConfigurationPlatforms) = postSolution\n'
    for p in "${all[@]}"; do
        g=$(guid_for "$p")
        local cfg
        for cfg in Debug Release; do
            printf '\t\t%s.%s|Any CPU.ActiveCfg = %s|Any CPU\n' "$g" "$cfg" "$cfg"
            printf '\t\t%s.%s|Any CPU.Build.0 = %s|Any CPU\n' "$g" "$cfg" "$cfg"
        done
    done
    printf '\tEndGlobalSection\n'
    printf 'EndGlobal\n'
}

if [ "$CHECK" = 1 ]; then
    if [ ! -f "$SLN" ]; then
        echo "cs-projects: missing $SLN"
        status=1
    elif ! diff -q <(sln_text) "$SLN" >/dev/null; then
        echo "cs-projects: stale $SLN (run 'bash test/cs-projects.sh')"
        status=1
    fi
else
    sln_text > "$SLN"
    echo "cs-projects: wrote $count project(s) and Pal.Tests.sln"
fi

if [ $status -eq 0 ] && [ "$CHECK" = 1 ]; then
    echo "cs-projects: OK ($count project(s) + Pal.Tests.sln)"
fi
exit $status
